ruleOrdinalDigits :: Rule
ruleOrdinalDigits = Rule
  { name = "ordinal (digits)"
  , pattern = [regex "0*([\\d૦-૯]+) ?(મું|મો|મી|માં|મા)"]
  , prod = \tokens -> case tokens of
      (Token RegexMatch (GroupMatch (match:_)):_) ->
        let clean = Text.map (\c -> HashMap.lookupDefault c c gujaratiDigitMap) match
        in ordinal <$> parseInt clean
      _ -> Nothing
  }

