ruleOrdinals :: Rule
ruleOrdinals = Rule
  { name = "ordinals (first..tenth)"
  , pattern =
    [ regex "(પ્રથમ|પહેલું|પહેલો|પહેલી|પહેલાં|પહેલા|દ્વિતીય|બીજું|બીજો|બીજી|બીજાં|બીજા|તૃતીય|ત્રીજું|ત્રીજો|ત્રીજી|ત્રીજાં|ત્રીજા|ચોથું|ચોથો|ચોથી|ચોથાં|ચોથા|પાંચમું|પાંચમો|પાંચમી|પાંચમાં|પાંચમા|છઠ્ઠું|છઠ્ઠો|છઠ્ઠી|છઠ્ઠાં|છઠ્ઠા|સાતમું|સાતમો|સાતમી|સાતમા|આઠમું|આઠમો|આઠમી|આઠમા|નવમું|નવમો|નવમી|નવમા|દસમું|દસમો|દસમી|દસમા|છેલ્લું|છેલ્લો|છેલ્લી|છેલ્લાં|છેલ્લા|આખરી)"
    ]
  , prod = \tokens -> case tokens of
      (Token RegexMatch (GroupMatch (match:_)):_) ->
        ordinal <$> HashMap.lookup match ordinalsMap
      _ -> Nothing
  }

